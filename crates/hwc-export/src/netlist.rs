//! Netlist Export (SPICE Format)
//!
//! Generates SPICE netlists from the routing graph for circuit simulation.
//! SPICE (Simulation Program with Integrated Circuit Emphasis) is the industry
//! standard format for analog circuit simulation.
//!
//! # Three-File SPICE Suite
//!
//! Generates three specialized SPICE files for different use cases:
//! - circuit.sp: Pure DUT (Device Under Test) with no stimulus
//! - dc.sp: DC operating point test with voltage sources from net declarations
//! - tran.sp: Transient analysis with pulsed stimulus for waveform plotting

use compact_str::CompactString;
use hwc_compiler::SymbolTable;
use hwc_engine::HardwareSpace;
use std::path::Path;

/// Stimulus generation mode for SPICE export
#[derive(Debug, Clone, Copy)]
enum StimulusMode {
    /// No stimulus - pure circuit only
    None,
    /// DC voltage sources with .op directive
    DcOperatingPoint,
    /// Pulsed voltage sources with .tran directive
    Transient,
}

/// Generate SPICE netlist suite (3 files in spice/ subdirectory)
pub fn export(
    space: &HardwareSpace,
    symbol_table: &SymbolTable,
    output_dir: &Path,
    physical_netlist: Option<&hwc_compiler::alignment::PhysicalNetlist>,
    space_def: Option<&hwc_parser::SpaceDefinition>,
) -> Result<(), Box<dyn std::error::Error>> {
    // Create spice subdirectory
    let spice_dir = output_dir.join("spice");
    std::fs::create_dir_all(&spice_dir)?;

    // Generate circuit body (reused by all variants)
    let circuit_body = generate_circuit_body(space, symbol_table, physical_netlist)?;

    // 1. Raw circuit (DUT only - no stimulus)
    let circuit_content = format!(
        "* Hardware Script Pure Circuit (DUT)\n\
         * Space: {}\n\
         * Generated by hwc v0.1.6\n\
         * Format: SPICE3\n\n\
         {}\
         .end\n",
        space.name, circuit_body
    );
    std::fs::write(spice_dir.join("circuit.sp"), circuit_content)?;

    // 2. DC operating point test
    let dc_stimulus = generate_stimulus(space_def, StimulusMode::DcOperatingPoint, physical_netlist);
    let dc_content = format!(
        "* Hardware Script DC Operating Point Test\n\
         * Space: {}\n\
         * Generated by hwc v0.1.6\n\
         * Format: SPICE3\n\n\
         {}\n\
         * ========================================\n\
         * STIMULUS & ANALYSIS\n\
         * ========================================\n\
         {}\
         .end\n",
        space.name, circuit_body, dc_stimulus
    );
    std::fs::write(spice_dir.join("dc.sp"), dc_content)?;

    // 3. Transient waveform test
    let tran_stimulus = generate_stimulus(space_def, StimulusMode::Transient, physical_netlist);
    let tran_content = format!(
        "* Hardware Script Transient Waveform Test\n\
         * Space: {}\n\
         * Generated by hwc v0.1.6\n\
         * Format: SPICE3\n\n\
         {}\n\
         * ========================================\n\
         * STIMULUS & ANALYSIS\n\
         * ========================================\n\
         {}\
         .end\n",
        space.name, circuit_body, tran_stimulus
    );
    std::fs::write(spice_dir.join("tran.sp"), tran_content)?;

    // Report to user
    let component_count = space.netlist.component_count();
    let pour_net_count = space.pours.iter().filter(|p| p.net.is_some()).count();
    let total_nets = space.netlist.num_nets() + pour_net_count;

    println!(
        "✅ SPICE Suite: {}/spice/ ({} components, {} nets)",
        output_dir.display(),
        component_count,
        total_nets
    );
    println!("   ├─ circuit.sp (raw DUT)");
    println!("   ├─ dc.sp (DC operating point)");
    println!("   └─ tran.sp (transient waveform)");

    Ok(())
}

/// Generate stimulus section based on mode
fn generate_stimulus(
    space_def: Option<&hwc_parser::SpaceDefinition>,
    mode: StimulusMode,
    physical_netlist: Option<&hwc_compiler::alignment::PhysicalNetlist>,
) -> String {
    let mut stimulus = String::new();

    match mode {
        StimulusMode::None => {
            // No stimulus
            return stimulus;
        }
        StimulusMode::DcOperatingPoint => {
            // Generate DC voltage sources from net declarations
            if let Some(space_def) = space_def {
                for net_decl in &space_def.nets {
                    if let Some(potential_mv) = net_decl.potential_mv {
                        let net_name = net_decl.name.as_str();
                        let voltage_v = potential_mv as f64 / 1000.0; // Convert mV to V
                        stimulus.push_str(&format!("V_{} {} 0 DC {:.3}\n", net_name, net_name, voltage_v));
                    }
                }
            }
            stimulus.push_str("Vgnd GND 0 0\n");
            stimulus.push_str(".op\n");
        }
        StimulusMode::Transient => {
            // Generate pulsed voltage sources for transient analysis
            if let Some(space_def) = space_def {
                for net_decl in &space_def.nets {
                    if let Some(potential_mv) = net_decl.potential_mv {
                        let net_name = net_decl.name.as_str();
                        let voltage_v = potential_mv as f64 / 1000.0; // Convert mV to V
                        
                        if voltage_v > 0.0 {
                            // Create pulse: PULSE(Vlow Vhigh Tdelay Trise Tfall Twidth Tperiod)
                            stimulus.push_str(&format!(
                                "V_{} {} 0 PULSE(0 {:.3} 10ns 1ns 1ns 50ns 100ns)\n",
                                net_name, net_name, voltage_v
                            ));
                        } else {
                            // Ground or 0V nets stay at DC 0
                            stimulus.push_str(&format!("V_{} {} 0 DC 0\n", net_name, net_name));
                        }
                    }
                }
            }
            stimulus.push_str("Vgnd GND 0 0\n");
            stimulus.push_str(".tran 200ns\n");
            
            // Add automatic plot directive for signal and power nets
            let mut plot_traces = Vec::new();
            
            if let Some(space_def) = space_def {
                for net_decl in &space_def.nets {
                    // Auto-plot signal and power nets
                    match net_decl.classification {
                        hwc_parser::NetClassification::Signal |
                        hwc_parser::NetClassification::Power => {
                            plot_traces.push(format!("V({})", net_decl.name));
                        }
                        _ => {}
                    }
                }
            }
            
            // Add currents from all extracted devices
            if let Some(netlist) = physical_netlist {
                for device in &netlist.devices {
                    // Get device type prefix (R, C, L, M, etc.)
                    let prefix = if let Some(type_name) = netlist.device_registry.get_name(device.device_type_id) {
                        type_name.chars().next().unwrap_or('X')
                    } else {
                        'X'
                    };
                    plot_traces.push(format!("I({}{})", prefix, device.name));
                }
            }
            
            // Emit plot directive if we have traces
            if !plot_traces.is_empty() {
                stimulus.push_str(&format!(".plot tran {}\n", plot_traces.join(" ")));
            }
        }
    }

    stimulus
}

/// Generate the circuit body (devices and nets) - reused by all SPICE variants
fn generate_circuit_body(
    space: &HardwareSpace,
    symbol_table: &SymbolTable,
    physical_netlist: Option<&hwc_compiler::alignment::PhysicalNetlist>,
) -> Result<String, Box<dyn std::error::Error>> {
    let mut netlist_str = String::new();

    // Emit nets as comments for reference
    let net_count = space.netlist.num_nets();

    // Collect nets from pours
    let mut pour_nets: rustc_hash::FxHashSet<CompactString> = rustc_hash::FxHashSet::default();
    for pour in &space.pours {
        if let Some(ref net_name) = pour.net {
            pour_nets.insert(net_name.clone());
        }
    }

    let total_nets = net_count + pour_nets.len();

    if total_nets > 0 {
        netlist_str.push_str("* ========================================\n");
        netlist_str.push_str("* NETS\n");
        netlist_str.push_str("* ========================================\n");

        // Emit nets from pours (silicon regions, metal layers)
        // Group merged regions together for parasitic extraction
        let mut merged_regions: rustc_hash::FxHashMap<
            CompactString,
            Vec<&hwc_engine::space::PourMetadata>,
        > = rustc_hash::FxHashMap::default();
        let mut standalone_pours = Vec::new();

        for pour in &space.pours {
            if let Some(ref merged_id) = pour.merged_region_id {
                merged_regions
                    .entry(merged_id.clone())
                    .or_default()
                    .push(pour);
            } else {
                standalone_pours.push(pour);
            }
        }

        // Emit merged regions (treat as single electrical node)
        for (merged_id, pours) in &merged_regions {
            if let Some(first_pour) = pours.first() {
                if let Some(ref net_name) = first_pour.net {
                    // Calculate total area for merged region
                    let total_area: i64 = pours.iter().map(|p| p.area_nm2).sum();

                    netlist_str.push_str(&format!(
                        "* Net: {} (merged region: {}, {} instances, total area: {} nm², material: {}, z: {:.4}mm)\n",
                        net_name,
                        merged_id,
                        pours.len(),
                        total_area,
                        first_pour.material_name,
                        first_pour.z_bottom_nm as f64 / 1_000_000.0
                    ));
                    netlist_str
                        .push_str("*   Parasitic extraction: Treat as single electrical node\n");
                }
            }
        }

        // Emit standalone pours
        for pour in standalone_pours {
            if let Some(ref net_name) = pour.net {
                netlist_str.push_str(&format!(
                    "* Net: {} (pour: {}, material: {}, z: {:.4}mm)\n",
                    net_name,
                    pour.name,
                    pour.material_name,
                    pour.z_bottom_nm as f64 / 1_000_000.0
                ));
            }
        }

        // Emit nets from netlist arena (discrete component connections)
        for net_id in space.netlist.all_net_ids() {
            if let Some(net) = space.netlist.get_net(net_id) {
                let material_name = space
                    .material_registry
                    .get_name(net.material)
                    .unwrap_or("Unknown");
                netlist_str.push_str(&format!(
                    "* Net: {} (width={}nm, material={})\n",
                    net.name, net.width_nm, material_name
                ));

                // List connected pins
                if !net.pins.is_empty() {
                    netlist_str.push_str("*   Connected pins:\n");
                    for pin_id in &net.pins {
                        if let Some(pin) = space.netlist.get_pin(*pin_id) {
                            if let Some(comp) = space.netlist.get_component(pin.parent_component) {
                                netlist_str
                                    .push_str(&format!("*     - {}.{}\n", comp.name, pin.name));
                            }
                        }
                    }
                }
            }
        }
        netlist_str.push('\n');
    }

    // Emit components as SPICE devices
    // If a physical netlist is present, skip schematic-level components to avoid
    // conflicting with extracted M devices (prevents LTspice subcircuit conflicts)
    let is_physical_mode = physical_netlist.is_some();
    let component_count = space.netlist.component_count();
    if component_count > 0 && !is_physical_mode {
        netlist_str.push_str("* ========================================\n");
        netlist_str.push_str("* COMPONENTS (Schematic-Level Subcircuits)\n");
        netlist_str.push_str("* ========================================\n");

        for i in 0..component_count {
            let comp_id = hwc_engine::netlist::ComponentId::new(i as u32);
            if let Some(component) = space.netlist.get_component(comp_id) {
                // Get component pins
                let pins = space.netlist.get_component_pins(comp_id);

                // Build net list for this component
                // v0.1.6 Item #13: Use pin net assignments from entity graph (from net: block)
                let mut net_names = Vec::new();
                for pin_id in &pins {
                    if let Some(pin) = space.netlist.get_pin(*pin_id) {
                        // First, try to get net assignment from entity graph component pins
                        // (these come from the net: block in component placement)
                        let entity_graph_net = space
                            .entity_graph
                            .get_component_pins()
                            .iter()
                            .find(|vp| {
                                vp.component_name == component.name && vp.pin_name == pin.name
                            })
                            .and_then(|vp| vp.net.clone());

                        if let Some(net_name) = entity_graph_net {
                            // Use net assignment from net: block
                            net_names.push(net_name);
                        } else if let Some(net_id) = pin.connected_net {
                            // Fall back to netlist arena connection (from routing)
                            if let Some(net) = space.netlist.get_net(net_id) {
                                net_names.push(net.name.clone());
                            } else {
                                net_names.push(format!("node_{}", net_id.raw()).into());
                            }
                        } else {
                            // No connection - floating pin
                            net_names.push(format!("nc_{}", pin_id.raw()).into());
                        }
                    }
                }

                // Emit SPICE device based on component type
                match component.component_type.to_uppercase().as_str() {
                    "NMOS" | "PMOS" => {
                        // MOSFET: M<name> <drain> <gate> <source> <bulk> <model>
                        // Assume pin order: Gate, Source, Drain, Bulk
                        if net_names.len() >= 3 {
                            let gate = net_names.first().cloned().unwrap_or_else(|| "0".into());
                            let source = net_names.get(1).cloned().unwrap_or_else(|| "0".into());
                            let drain = net_names.get(2).cloned().unwrap_or_else(|| "0".into());
                            let bulk = net_names.get(3).cloned().unwrap_or_else(|| "0".into());

                            netlist_str.push_str(&format!(
                                "M{} {} {} {} {} {}\n",
                                component.name, drain, gate, source, bulk, component.component_type
                            ));
                        } else {
                            netlist_str.push_str(&format!(
                                "* WARNING: {} has insufficient pins for MOSFET\n",
                                component.name
                            ));
                        }
                    }
                    _ => {
                        // Generic subcircuit: X<name> <nets...> <type>
                        netlist_str.push_str(&format!(
                            "X{} {} {}\n",
                            component.name,
                            net_names.join(" "),
                            component.component_type
                        ));
                    }
                }
            }
        }
        netlist_str.push('\n');
    }

    // GAP 7 Phase 4: EXTRACTED DEVICES (Intent-Based Atom Architecture)
    // Devices are extracted from explicit device: bindings during alignment validation
    // This section outputs devices using their SPICE metadata from device definitions
    if let Some(netlist) = physical_netlist {
        if !netlist.devices.is_empty() {
            netlist_str.push_str("\n* ========================================\n");
            netlist_str.push_str("* EXTRACTED DEVICES\n");
            netlist_str.push_str("* ========================================\n");

            for device in &netlist.devices {
                // Get device type name from the registry
                let device_type_name = netlist
                    .device_registry
                    .get_name(device.device_type_id)
                    .ok_or_else(|| {
                        format!(
                            "Device '{}' has invalid device_type_id: {}",
                            device.name, device.device_type_id
                        )
                    })?;

                // Look up device definition from symbol table to get SPICE metadata
                let device_def = symbol_table.get_device(device_type_name).map_err(|e| {
                    format!(
                        "Device '{}' of type '{}' not found in symbol table: {}",
                        device.name, device_type_name, e
                    )
                })?;

                // Get SPICE export info - ERROR if not defined
                let spice_info = device_def.spice_info().ok_or_else(|| {
                    format!(
                        "Device '{}' of type '{}' has no SPICE export metadata. \
                         Add 'spice_info' to the device definition.",
                        device.name, device_type_name
                    )
                })?;

                // Build SPICE card using metadata from device definition
                netlist_str.push(spice_info.prefix);
                netlist_str.push_str(&device.name);

                // Add terminals in the order specified by device definition
                for terminal_name in &spice_info.terminal_order {
                    let net_name = device.terminals.get(terminal_name.as_str()).ok_or_else(|| {
                        format!(
                            "Device '{}' missing required terminal '{}' (device type: {})",
                            device.name, terminal_name, device_type_name
                        )
                    })?;
                    netlist_str.push(' ');
                    netlist_str.push_str(net_name);
                }

                // Add model name if specified
                if let Some(ref model) = spice_info.model_name {
                    netlist_str.push(' ');
                    netlist_str.push_str(model);
                }

                // Add parameters specified in device definition
                for param_name in &spice_info.parameters {
                    let param_value = device.parameters.get(param_name.as_str()).ok_or_else(|| {
                        format!(
                            "Device '{}' missing required parameter '{}' (device type: {})",
                            device.name, param_name, device_type_name
                        )
                    })?;
                    
                    // Format parameter based on name convention
                    if param_name.as_str() == "R" || param_name.as_str() == "C" || param_name.as_str() == "L" {
                        // Direct value for passive components
                        netlist_str.push_str(&format!(" {:.2}", param_value));
                    } else {
                        // Named parameter for active components
                        netlist_str.push_str(&format!(" {}={:.2}u", param_name, param_value));
                    }
                }

                netlist_str.push('\n');
            }
            netlist_str.push('\n');
        }
    } else {
        // No physical netlist available (Artist Mode or no device bindings)
        println!("   ├─ Device extraction skipped (requires module with explicit bindings)");
        println!("   ├─ Use 'device: DeviceName.terminal' to bind pours to devices");
        netlist_str.push_str("* ========================================\n");
        netlist_str.push_str("* DEVICE EXTRACTION REQUIRES EXPLICIT BINDINGS\n");
        netlist_str.push_str("* Use 'device: DeviceName.terminal' property\n");
        netlist_str.push_str("* ========================================\n\n");
    }

    Ok(netlist_str)
}
